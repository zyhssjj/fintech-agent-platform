/* Run with bundled Playwright on the host. Screenshots stay in ignored runtime. */
const { chromium } = require("playwright");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const catalog = JSON.parse(fs.readFileSync(path.join(__dirname, "../config/catalog_v2.json"), "utf8"));

async function run() {
  const artifacts = path.join(__dirname, "../runtime/test-artifacts");
  fs.mkdirSync(artifacts, { recursive: true });
  const browser = await chromium.launch({ channel: "msedge", headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  const rootSelect = () => page.locator('#ingestion-domain select[data-depth="0"]');
  try {
    await page.goto("http://127.0.0.1:8201/#ingestion");
    await page.locator("#ingestion-company option").first().waitFor({ state: "attached" });
    assert.equal(await page.locator("#ingestion-company option").count(), 3);
    assert.equal(await page.locator(".directory-guide").isVisible(), true);
    assert.equal(await page.locator("#ingestion-domain select").count(), 1);
    assert.equal(await page.locator("#ingestion-submit").isDisabled(), true);
    let checked = 0;
    for (const platform of catalog.platforms) {
      await page.locator("#ingestion-company").selectOption(platform.code);
      for (const leaf of platform.leaves) {
        await rootSelect().selectOption(leaf.level1);
        assert.equal(await page.locator(".tree-root strong").innerText(), leaf.level1);
        assert.equal(await page.locator("#ingestion-domain select").count(), 1);
        await page.locator(`[data-secondary-path="${leaf.level1}/${leaf.level2}"]`).click();
        assert.ok((await page.locator(".tertiary-definition").innerText()).includes(leaf.level2_definition));
        assert.equal(await page.locator(".tertiary-item").count(), platform.leaves.filter((item) => item.level1 === leaf.level1 && item.level2 === leaf.level2).length);
        const leafIndex = await page.locator("[data-leaf-path]").evaluateAll((buttons, domainPath) => buttons.findIndex((button) => button.dataset.leafPath === domainPath), leaf.domain_path);
        assert.ok(leafIndex >= 0, `missing leaf button: ${leaf.domain_path}`);
        const leafButton = page.locator("[data-leaf-path]").nth(leafIndex);
        assert.ok((await leafButton.innerText()).includes(`${leaf.related_files.length} 项相关文件`));
        await leafButton.click();
        const detail = await page.locator("#catalog-leaf-detail").innerText();
        assert.ok(detail.includes(leaf.level3), `${platform.name} ${leaf.domain_path}: ${detail}`);
        assert.ok(detail.includes(leaf.classification_standard));
        assert.equal(await page.locator("#catalog-leaf-detail > ol > li").count(), leaf.related_files.length);
        assert.equal(await page.locator("#file-input").isDisabled(), false);
        await page.locator("#file-input").setInputFiles({ name: "ui-test.md", mimeType: "text/markdown", buffer: Buffer.from("test") });
        assert.equal(await page.locator("#ingestion-submit").isDisabled(), false);
        await rootSelect().selectOption("");
        assert.equal(await page.locator(".directory-guide").isVisible(), true);
        assert.equal(await page.locator(".tree-branch").count(), 0);
        assert.equal(await page.locator("#selected-files").innerText(), "");
        assert.equal(await page.locator("#file-input").evaluate((element) => element.files.length), 0);
        assert.equal(await page.locator("#ingestion-submit").isDisabled(), true);
        checked += 1;
      }
    }
    await page.locator("#ingestion-company").selectOption(catalog.platforms[0].code);
    const leaf = catalog.platforms[0].leaves[0];
    await rootSelect().selectOption(leaf.level1);
    const rootNode = await page.locator(".tree-root").boundingBox();
    const branchTree = await page.locator(".tree-branches").boundingBox();
    const firstBranch = await page.locator(".tree-branch").first().boundingBox();
    const firstNodeDot = await page.locator(".tree-node-dot").first().boundingBox();
    assert.ok(Math.abs((rootNode.y + rootNode.height / 2) - (branchTree.y + branchTree.height / 2)) <= 1, "root node must be vertically centered against the branch tree");
    assert.ok(firstNodeDot.x + firstNodeDot.width < firstBranch.x, "connector dot must not overlap the branch card border");
    await page.locator(`[data-secondary-path="${leaf.level1}/${leaf.level2}"]`).click();
    const preview = await page.locator(".tertiary-list").boundingBox();
    const panel = await page.locator(".directory-panel").boundingBox();
    assert.ok(preview.x >= panel.x && preview.x + preview.width <= panel.x + panel.width && preview.y + preview.height <= panel.y + panel.height, "preview must stay inside the directory panel");
    await page.screenshot({ path: path.join(artifacts, "v2-preview-desktop.png"), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.waitForFunction(() => document.querySelector("#sidebar").getBoundingClientRect().right <= 1);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
    await page.screenshot({ path: path.join(artifacts, "v2-preview-mobile.png"), fullPage: true });
    await page.setViewportSize({ width: 1440, height: 1000 });
    const leafIndex = await page.locator("[data-leaf-path]").evaluateAll((buttons, domainPath) => buttons.findIndex((button) => button.dataset.leafPath === domainPath), leaf.domain_path);
    await page.locator("[data-leaf-path]").nth(leafIndex).click();
    const left = await page.locator(".directory-panel").boundingBox();
    const right = await page.locator(".ingestion-actions-panel").boundingBox();
    assert.ok(left.x + left.width <= right.x, "01 and 02 must be side-by-side");
    assert.equal(await page.locator(".pipeline-card").count(), 0);
    let jobPolls = 0;
    let jobOutcome = "succeeded";
    await page.route("**/api/ingestion/upload", (route) => route.fulfill({ status: 202, contentType: "application/json", body: JSON.stringify({ id: "ui-progress-job" }) }));
    await page.route("**/api/ingestion/jobs/ui-progress-job", (route) => {
      jobPolls += 1;
      const processing = jobOutcome === "succeeded" && jobPolls === 1;
      return route.fulfill({ contentType: "application/json", body: JSON.stringify({ status: processing ? "processing" : jobOutcome, progress: processing ? 25 : 100, message: processing ? "正在解析文档" : jobOutcome === "failed" ? "测试认证失败" : "文档已完成入库" }) });
    });
    await page.locator("#file-input").setInputFiles({ name: "progress.md", mimeType: "text/markdown", buffer: Buffer.from("test") });
    await page.locator("#ingestion-submit").click();
    await page.waitForFunction(() => document.querySelector("#ingestion-status progress")?.value === 25);
    assert.equal(await page.locator("#ingestion-submit").isDisabled(), true);
    assert.equal(await page.locator("#ingestion-status").evaluate((element) => Boolean(element.closest(".ingestion-actions-panel"))), true);
    await page.waitForFunction(() => document.querySelector("#ingestion-status").dataset.status === "succeeded");
    assert.equal(await page.locator("#ingestion-status progress").getAttribute("value"), "100");
    await page.screenshot({ path: path.join(artifacts, "v2-desktop.png"), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.waitForFunction(() => document.querySelector("#sidebar").getBoundingClientRect().right <= 1);
    assert.equal(await page.locator(".company-trigger-main").isVisible(), true);
    await page.screenshot({ path: path.join(artifacts, "v2-mobile.png"), fullPage: true });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true, "mobile overflow");
    await page.locator("#company-select").click();
    assert.equal(await page.locator(".company-option-copy").first().isVisible(), true);
    await page.locator("#company-select").click();
    await page.setViewportSize({ width: 1440, height: 1000 });
    jobOutcome = "failed";
    await page.locator("#file-input").setInputFiles({ name: "retry.md", mimeType: "text/markdown", buffer: Buffer.from("test") });
    await page.locator("#ingestion-submit").click();
    await page.waitForFunction(() => document.querySelector("#ingestion-status").dataset.status === "failed");
    assert.ok((await page.locator("#ingestion-status").innerText()).includes("测试认证失败"));
    await page.locator('[data-view="search"]').click();
    await page.locator('#search-domains select[data-depth="0"]').selectOption(leaf.level1);
    await page.locator('#search-domains select[data-depth="1"]').selectOption(`${leaf.level1}/${leaf.level2}`);
    await page.locator('#search-domains select[data-depth="2"]').selectOption(leaf.domain_path);
    await page.locator("#search-query").fill("V2 验收资料内容是什么");
    const request = page.waitForRequest((req) => req.url().endsWith("/api/search"));
    await page.locator("#search-submit").click();
    assert.deepEqual((await request).postDataJSON().domain_paths, [leaf.domain_path]);
    await page.locator('[data-view="documents"]').click();
    const docsRequest = page.waitForRequest((req) => req.url().includes("/api/documents?") && new URL(req.url()).searchParams.get("domain_paths") === leaf.level1);
    await page.locator('#document-domain select[data-depth="0"]').selectOption(leaf.level1);
    await docsRequest;
    await page.route("**/api/credentials", async (route) => {
      if (route.request().method() !== "POST") return route.continue();
      return route.fulfill({ status: 200, contentType: "application/json", body: JSON.stringify({ id: "c-ui-scope", name: "权限测试智能体", api_key: "wk_ui_test", knowledge_scopes: route.request().postDataJSON().knowledge_scopes, enabled: true }) });
    });
    await page.locator('[data-view="agents"]').click();
    await page.locator("#agent-add").click();
    assert.equal(await page.locator(".agent-scope-platform").count(), 3);
    assert.equal(await page.locator("[data-agent-leaf]").count(), 111);
    assert.equal(await page.locator("#agent-create-submit").isDisabled(), true);
    const permissionLeaf = catalog.platforms[0].leaves[0];
    const permissionInput = page.locator(`[data-agent-company="${catalog.platforms[0].code}"][data-agent-leaf="${permissionLeaf.domain_path}"]`);
    await permissionInput.check();
    assert.equal(await page.locator("#agent-create-submit").isDisabled(), false);
    const permissionPlatform = page.locator(`[data-agent-platform="${catalog.platforms[0].code}"]`);
    assert.equal(await permissionPlatform.evaluate((input) => input.indeterminate), true);
    assert.ok((await page.locator("#agent-scope-summary").innerText()).includes("1 个三级事项"));
    await permissionPlatform.check();
    assert.ok((await page.locator("#agent-scope-summary").innerText()).includes(`${catalog.platforms[0].leaves.length} 个三级事项`));
    await permissionPlatform.uncheck();
    assert.equal(await page.locator("#agent-create-submit").isDisabled(), true);
    await permissionInput.check();
    await page.screenshot({ path: path.join(artifacts, "agent-credential-scope.png"), fullPage: true });
    await page.locator('#agent-form input[name="name"]').fill("权限测试智能体");
    const credentialRequest = page.waitForRequest((req) => req.url().endsWith("/api/credentials") && req.method() === "POST");
    await page.locator("#agent-create-submit").click();
    const credentialPayload = (await credentialRequest).postDataJSON();
    assert.deepEqual(credentialPayload.knowledge_scopes, [{ company_code: catalog.platforms[0].code, domain_paths: [permissionLeaf.domain_path] }]);
    await page.waitForFunction(() => document.querySelector("#key-dialog").open);
    assert.equal(await page.locator("#key-dialog").evaluate((dialog) => dialog.open), true);
    await page.locator("#key-dialog [data-dialog-close]").last().click();
    await page.locator('[data-view="users"]').click();
    await page.locator("#user-add").click();
    assert.ok(await page.locator('.user-credential-option input[name="credential_ids"]').count() >= 1);
    await page.locator('.user-credential-option input[name="credential_ids"]').first().check();
    assert.ok((await page.locator("#user-credential-summary").innerText()).includes("1 个凭证"));
    assert.equal(await page.locator("#user-dialog-title").innerText(), "新建用户");
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true, "user dialog mobile overflow");
    await page.setViewportSize({ width: 1440, height: 1000 });
    assert.deepEqual(errors, []);
    console.log(`PASS: desktop/mobile UI, ${checked} ingestion leaves, 111 permission leaves, user multi-credential form, granular credential payload, layout, progress, filters, no JS errors`);
  } finally { await browser.close(); }
}
run().catch((error) => { console.error(error); process.exitCode = 1; });
